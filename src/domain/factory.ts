import * as Crypto from 'expo-crypto';
import { Temporal } from '@js-temporal/polyfill';

import type { SharedDocument } from './models';
import { parseSharedDocument } from './schema';

export type NewDocumentInput = {
  title: string;
  organization: string;
  startsAt: string;
  endsAt: string;
  timeZone: string;
};

export function createDocument(input: NewDocumentInput): SharedDocument {
  return parseSharedDocument({
    schemaVersion: 1,
    documentId: Crypto.randomUUID(),
    organizationId: Crypto.randomUUID(),
    revision: 1,
    publishedAt: new Date().toISOString(),
    event: { ...input, accent: 'blue' },
    people: [],
    teams: [],
    tasks: [],
  });
}

